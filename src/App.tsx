import { useEffect, useMemo, useRef, useState } from 'react';
import type { ReactNode } from 'react';
import type { SearchResult } from '@shared/types';
import { DataSourceProvider, HttpDataSource, useCapabilities } from './data';
import type { DataSource } from './data';
import { FundamentalsDrawer, useEarningsMarkers } from './fundamentals';
import { LayoutSwitcher } from './layouts';
import { WatchlistPanel } from './watchlist';
import { WorkspaceProvider, useActiveChart } from './workspace';
import { Attribution, ChartPanel, ChartTypeSelector, SnapshotReadout, SymbolSearch, TimeframeSelector } from './ui';

/**
 * Dev-only: serve /api/* from MSW (mocks/) instead of the proxy. On by default in
 * `vite dev`; set VITE_USE_MOCKS=false to talk to the real proxy. Never active in
 * tests (they install their own MSW server) or in production builds (the branch is
 * statically dead there, so MSW is not bundled).
 */
const USE_MOCKS =
  import.meta.env.DEV && import.meta.env.MODE !== 'test' && import.meta.env.VITE_USE_MOCKS !== 'false';

let mocksStarted: Promise<unknown> | null = null;
function startMocks(): Promise<unknown> {
  // Memoised: StrictMode runs the gate's effect twice and a second `start()` would warn.
  mocksStarted ??= import('../mocks/browser')
    .then(({ worker }) => worker.start({ onUnhandledRequest: 'bypass', quiet: true }))
    .catch((e: unknown) => {
      // Service workers can be unavailable (some embedded browsers, private modes).
      // Render anyway: requests then reach the Vite proxy, and every data path shows
      // its real error state instead of the app staying blank.
      console.warn('[mocks] MSW service worker failed to start; falling through to /api proxy.', e);
    });
  return mocksStarted;
}

/** Holds the app back until the service worker is ready, or the first requests would escape it. */
function MockGate({ children }: { children: ReactNode }) {
  const [ready, setReady] = useState(!USE_MOCKS);
  useEffect(() => {
    if (!USE_MOCKS) return;
    let cancelled = false;
    startMocks().then(() => {
      if (!cancelled) setReady(true);
    });
    return () => {
      cancelled = true;
    };
  }, []);
  return ready ? <>{children}</> : null;
}

export interface AppProps {
  /** Override the data source (tests, or a future WebSocket-backed one). */
  dataSource?: DataSource;
}

export function App({ dataSource }: AppProps) {
  const ds = useMemo(() => dataSource ?? new HttpDataSource(), [dataSource]);
  return (
    <MockGate>
      <DataSourceProvider value={ds}>
        <WorkspaceProvider>
          <Shell />
        </WorkspaceProvider>
      </DataSourceProvider>
    </MockGate>
  );
}

/**
 * The application frame. ORCHESTRATOR-OWNED for Phase 5: workers fill the slots, they
 * do not edit this file.
 *
 *   toolbar:  [layouts] [search] [quote] ··· [timeframes] [chart type] [Financials]
 *   body:     [chart]  [watchlist sidebar]   (Financials opens as a full page over both)
 *   footer:   licence attribution
 */
function Shell() {
  const { chart, setSymbol, setTimeframe, setChartType } = useActiveChart();
  const capabilities = useCapabilities();
  const markers = useEarningsMarkers(chart.symbol);
  const [financialsOpen, setFinancialsOpen] = useState(false);
  const financialsButton = useRef<HTMLButtonElement>(null);

  function closeFinancials() {
    setFinancialsOpen(false);
    financialsButton.current?.focus(); // back where the user opened it
  }
  // Company names are known only after a search pick; other paths show the symbol alone.
  const [names, setNames] = useState<Record<string, string>>({});

  function select(result: SearchResult) {
    setNames((n) => ({ ...n, [result.symbol]: result.name }));
    setSymbol(result.symbol);
  }

  return (
    <div className="app-shell">
      <header className="toolbar">
        <LayoutSwitcher />
        <SymbolSearch onSelect={select} />
        <SnapshotReadout symbol={chart.symbol} name={names[chart.symbol] ?? null} />
        <div className="toolbar-spacer" />
        <TimeframeSelector value={chart.timeframe} onChange={setTimeframe} />
        <ChartTypeSelector value={chart.chartType} onChange={setChartType} />
        {capabilities?.fundamentals && (
          <button
            ref={financialsButton}
            type="button"
            className={`toolbar-toggle${financialsOpen ? ' active' : ''}`}
            aria-pressed={financialsOpen}
            onClick={() => setFinancialsOpen((o) => !o)}
          >
            Financials
          </button>
        )}
      </header>
      <div className="app-body">
        <div className="app-center">
          <main className="workspace">
            <ChartPanel symbol={chart.symbol} timeframe={chart.timeframe} chartType={chart.chartType} markers={markers} />
          </main>
        </div>
        <aside className="sidebar-right">
          <WatchlistPanel />
        </aside>
        {/* Full page over the chart and the watchlist, like TradingView. The chart stays
            mounted underneath, so it keeps its position when the page closes. */}
        {financialsOpen && <FundamentalsDrawer symbol={chart.symbol} onClose={closeFinancials} />}
      </div>
      <Attribution />
    </div>
  );
}
